"""Trusted-host CLI for serving a pinned, scoped MCP task.

The JSON host config must be provisioned outside agent-visible workspace by a
trusted controller. Never accept it as text generated by the agent.
"""
from __future__ import annotations

import argparse
import json
import os
import stat
from pathlib import Path
import sys

from .mcp_gateway import Gateway, HostTask, serve_stdio
from .telemetry import AuditLog


def load_host_config(path: Path) -> Gateway:
    requested_path = Path(path).absolute()
    if requested_path.is_symlink():
        raise ValueError('host configuration cannot be a symlink')
    config_path = requested_path.resolve(strict=True)
    mode = config_path.stat()
    if not stat.S_ISREG(mode.st_mode) or mode.st_mode & 0o022 or mode.st_uid != os.geteuid():
        raise ValueError('unsafe host configuration permissions')
    conf = json.loads(config_path.read_text(encoding='utf-8'))
    expected = {'task_id','objective','workspace','branch','base_commit',
                'read_scope','write_scope','audit_path','max_calls'}
    if not isinstance(conf, dict) or set(conf) != expected:
        raise ValueError('invalid host configuration schema')
    root = Path(conf['workspace']).resolve(strict=True)
    if config_path.is_relative_to(root) or requested_path.is_relative_to(root):
        raise ValueError('host config must be outside agent workspace')
    if not isinstance(conf['read_scope'],list) or not isinstance(conf['write_scope'],list) or any(
        not isinstance(p,str) for p in conf['read_scope']+conf['write_scope']):
        raise ValueError('invalid host scope configuration')
    task = HostTask(conf['task_id'], conf['objective'], root,
                    conf['branch'], conf['base_commit'],
                    frozenset(conf['read_scope']), frozenset(conf['write_scope']),conf['max_calls'])
    return Gateway(task, AuditLog(Path(conf['audit_path']), root))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--host-config', type=Path, required=True)
    args = parser.parse_args()
    try:
        gateway = load_host_config(args.host_config)
    except Exception as exc:
        # Errors only on stderr; no stdout protocol data.
        print(f'host setup refused: {type(exc).__name__}', file=sys.stderr)
        return 2
    serve_stdio(gateway)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
